import {test} from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,rm,readFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join,resolve} from 'node:path';
import {createServer} from 'node:http';
import {runCenterAssistant,assistantLocal,assistantContext,scopedAssistantCall,scopedAssistantTools} from '../desktop/scripts/agent/center-assistant.mjs';
import {writeCenterJson} from '../scripts/rssd-center-client.mjs';
const params={agentId:'codex',workspaceIds:['space-a'],text:'read'};
test('scoped MCP tools cannot widen scope or bypass the production executor',async()=>{
 const calls=[],remote=async(...args)=>{calls.push(args);return {};};
 const ctx={workspaceIds:['space-a'],client:{work:async()=>({workspaceId:'space-b'}),demands:async()=>[{id:'other',workspaceId:'space-a'}]}};
 await assert.rejects(scopedAssistantCall(ctx,'rssd_overview',{workspaceIds:'space-b'},remote));
 await assert.rejects(scopedAssistantCall(ctx,'rssd_demands',{workspaceId:'space-b'},remote));
 await assert.rejects(scopedAssistantCall(ctx,'rssd_work',{workId:'other'},remote));
 await assert.rejects(scopedAssistantCall(ctx,'rssd_edit_demand',{id:'other-outside'},remote));
 await assert.rejects(scopedAssistantCall(ctx,'rssd_submit',{},remote));assert.equal(calls.length,0);
 await scopedAssistantCall(ctx,'rssd_overview',{},remote);assert.equal(calls[0][1].workspaceIds,'space-a');
 assert.deepEqual(scopedAssistantTools([{name:'rssd_claim'},{name:'rssd_submit'},{name:'rssd_edit_demand'}]).map(t=>t.name),['rssd_edit_demand']);
});
test('ACP and stdio MCP stream real responses, resume, retain write identity, cancel and archive',async t=>{
 const home=await mkdtemp(join(tmpdir(),'rssd-assistant-')),calls=[];
 const original=process.env.RSSD_CENTER_TOKEN;process.env.RSSD_CENTER_TOKEN='rssd_device_'+'a'.repeat(48);
 const server=createServer(async(req,res)=>{
  let body='';for await(const chunk of req)body+=chunk;
  res.setHeader('content-type','application/json');
  if(req.url.startsWith('/api/rssd/v1/demands?'))return res.end(JSON.stringify([{id:'demand-a',workspaceId:'space-a'}]));
  const m=JSON.parse(body);calls.push(m);let result={};
  if(m.method==='initialize')result={protocolVersion:'2025-11-25'};
  if(m.method==='tools/list')result={tools:['rssd_overview','rssd_edit_demand','rssd_submit'].map(name=>({name,inputSchema:{type:'object'}}))};
  if(m.method==='tools/call')result={content:[{type:'text',text:JSON.stringify({actual:'center response',scope:m.params.arguments.workspaceIds})}]};
  res.end(JSON.stringify({jsonrpc:'2.0',id:m.id,result}));
 });
 await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
 t.after(async()=>{server.closeAllConnections();server.close();if(original===undefined)delete process.env.RSSD_CENTER_TOKEN;else process.env.RSSD_CENTER_TOKEN=original;await rm(home,{recursive:true,force:true});});
 await writeCenterJson(join(home,'connection.json'),{origin:'http://127.0.0.1:'+server.address().port,identity:{orgId:'org-a',workerId:'worker-a'}});
 const registry={launch:async()=>({command:process.execPath,args:[resolve('tests/fixtures/rssd-assistant-agent.mjs')]})};
 assert.equal((await runCenterAssistant(params,home,{registry})).state,'complete');
 let state=await assistantLocal('assistant_status',params,home);assert.match(state.history.find(e=>e.role==='assistant').text,/center response/);
 assert.equal(state.sessionId,'test-session');
 await runCenterAssistant({...params,text:'edit'},home,{registry});await runCenterAssistant({...params,text:'edit'},home,{registry});
 const edits=calls.filter(m=>m.method==='tools/call'&&m.params.name==='rssd_edit_demand');assert.equal(edits.length,2);assert.equal(edits[0].params.arguments.requestId,edits[1].params.arguments.requestId);assert.notEqual(edits[0].params.arguments.requestId,'model-generated-id');
 const running=runCenterAssistant({...params,text:'wait'},home,{registry});
 let ready=false;for(let i=0;i<200;i++){state=await assistantLocal('assistant_status',params,home);if(state.state==='running'&&state.message==='正在处理指令'){ready=true;break;}await new Promise(r=>setTimeout(r,25));}assert.equal(ready,true);
 await assert.rejects(runCenterAssistant(params,home,{registry}),/正在保存/);
 await assistantLocal('assistant_cancel',params,home);assert.equal((await running).state,'cancelled');
 state=await assistantLocal('assistant_status',params,home);assert.ok(state.history.length>0);
 const ctx=await assistantContext(home,params);assert.ok(!(await readFile(join(ctx.directory,'state.json'),'utf8')).includes(process.env.RSSD_CENTER_TOKEN));
 assert.deepEqual((await assistantLocal('assistant_reset',params,home)).history,[]);
 await writeCenterJson(join(ctx.directory,'state.json'),{state:'running',pid:2147483646,history:[{role:'user',text:'preserved'}]});assert.equal((await assistantLocal('assistant_status',params,home)).state,'interrupted');
});
