const PATTERNS=[[/^请填写 ([\w.-]+)$/,field=>[`Fill in ${field}.`,`${field} を入力してください。`]]];
const COLUMN={en:0,ja:1};

export function localizeMessage(message,language){
  const column=COLUMN[language];
  if(column===undefined||typeof message!=='string')return message;
  if(Object.hasOwn(MESSAGES,message))return MESSAGES[message][column];
  for(const [pattern,translate] of PATTERNS){const match=pattern.exec(message);if(match)return translate(match[1])[column];}
  return message;
}
