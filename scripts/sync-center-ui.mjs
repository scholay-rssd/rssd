// Copies the desktop work-centre view into the online Center, where it is the
// page at /rssd. The desktop tree is the canonical source: never edit the
// copies. `--check` fails when the Center's copy differs from this checkout.
import {readFile,writeFile,mkdir,readdir,rm} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {resolve,join,dirname} from 'node:path';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const source=join(root,'desktop/src'),frontend=join(root,'center/apps/frontend');
const target=join(frontend,'src/components/rssd/desktop-ui'),assets=join(frontend,'public/rssd-ui');
const check=process.argv.includes('--check');
const banner='Generated by scripts/sync-center-ui.mjs in scholay-rssd/rssd. Do not edit; change desktop/src and sync again.';

// Sources mirror their desktop paths so their relative imports keep resolving.
const preview=(await readdir(join(source,'center/preview'))).filter(name=>/\.(tsx?|css)$/.test(name)&&!name.includes('.test.')&&name!=='assets.ts').sort();
const outputs=new Map();
for(const path of [...preview.map(name=>'center/preview/'+name),'components/Icon.tsx'])outputs.set(path,await readFile(join(source,path)));

// The Center's own versions of the two modules that depend on the desktop build.
outputs.set('uiText.ts',Buffer.from(`// ${banner}
// The Center shows the Chinese source text; only {{placeholders}} are filled.
export function tr(source: string, vars?: Record<string, unknown>): string {
  return vars ? source.replace(/\\{\\{(\\w+)\\}\\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match)) : source;
}
`));
const branding=(await readdir(join(root,'sites/branding'))).filter(name=>name==='academic.png'||name.endsWith('-bw-v8.webp')).sort();
const platforms=(await readdir(join(source,'center/preview/assets'))).filter(name=>name.endsWith('.svg')).sort();
const title=name=>({linkedin:'LinkedIn',x:'X'}[name]||name[0].toUpperCase()+name.slice(1));
outputs.set('center/preview/assets.ts',Buffer.from(`// ${banner}
// Brand images served by the Center from /rssd-ui.
const sites: Record<string, string> = ${JSON.stringify(Object.fromEntries(branding.map(name=>[name==='academic.png'?'academic':name.replace('-bw-v8.webp',''),'/rssd-ui/sites/'+name])),null,2)};
const platforms: Record<string, string> = ${JSON.stringify(Object.fromEntries(platforms.map(name=>[title(name.replace('.svg','')),'/rssd-ui/platforms/'+name])),null,2)};
export const siteImage = (workspaceId: string): string | undefined => sites[workspaceId];
export const platformImage = (name: string): string | undefined => platforms[name];
`));

// The desktop's default palette (Paper, light and dark), scoped to the Center page.
const styles=await readFile(join(source,'styles.css'),'utf8');
const block=selector=>{
  const start=styles.indexOf('\n'+selector+' {');if(start<0)throw Error('Desktop palette block not found: '+selector);
  const end=styles.indexOf('\n}',start);return styles.slice(styles.indexOf('{',start)+1,end);
};
outputs.set('tokens.css',Buffer.from(`/* ${banner} */
.rssd-desktop {${block(':root')}
  font-family: var(--ui);
  -webkit-font-smoothing: antialiased;
  color: var(--ink);
  background: var(--panel);
}
.rssd-desktop[data-mode="dark"] {${block('[data-mode="dark"]')}${block('[data-palette="paper"][data-mode="dark"]')}
}
`));

const files=new Map();
// The UI typeface, as the desktop bundles it: the Latin subsets only, since the
// Center's Chinese text uses the reader's system fonts either way.
const font=join(root,'desktop/node_modules/@fontsource-variable/inter-tight');
const faces=(await readFile(join(font,'index.css'),'utf8').catch(()=>{throw Error('Install the desktop dependencies first: npm run desktop:install');}))
  .split(/(?=\/\* inter-tight-)/).filter(face=>/^\/\* inter-tight-latin(-ext)?-wght-normal \*\//.test(face));
if(faces.length!==2)throw Error('Inter Tight Latin faces not found in the desktop font package');
outputs.set('fonts.css',Buffer.from(`/* ${banner} */\n`+faces.join('').replace(/url\(\.\/files\/([\w.-]+)\)/g,(_,name)=>{files.set('fonts/'+name,null);return 'url(/rssd-ui/fonts/'+name+')';}).trim()+'\n'));
for(const path of [...files.keys()])files.set(path,await readFile(join(font,'files',path.slice('fonts/'.length))));
for(const name of branding)files.set('sites/'+name,await readFile(join(root,'sites/branding',name)));
for(const name of platforms)files.set('platforms/'+name,await readFile(join(source,'center/preview/assets',name)));

const sha=bytes=>createHash('sha256').update(bytes).digest('hex');
const manifest={version:2,source:'https://github.com/scholay-rssd/rssd/tree/main/desktop/src',license:'MIT',
  files:[...outputs].map(([path,bytes])=>({path,sha256:sha(bytes)})),assets:[...files].map(([path,bytes])=>({path,sha256:sha(bytes)}))};
const manifestBytes=Buffer.from(JSON.stringify(manifest,null,2)+'\n');

const listed=async(dir,prefix='')=>{const found=[];for(const entry of await readdir(dir,{withFileTypes:true}).catch(()=>[])){const path=prefix+entry.name;if(entry.isDirectory())found.push(...await listed(join(dir,entry.name),path+'/'));else found.push(path);}return found;};
if(check){
  const differs=[];
  for(const [dir,wanted] of [[target,new Map([...outputs,['manifest.json',manifestBytes]])],[assets,files]]){
    for(const [path,bytes] of wanted)if(!(await readFile(join(dir,path)).catch(()=>Buffer.alloc(0))).equals(bytes))differs.push(path);
    for(const path of await listed(dir))if(!wanted.has(path))differs.push(path+' (not from the desktop source)');
  }
  if(differs.length)throw Error('Center UI differs from its desktop source; run npm run center:ui:sync:\n  '+differs.join('\n  '));
}else{
  for(const [dir,wanted] of [[target,new Map([...outputs,['manifest.json',manifestBytes]])],[assets,files]]){
    await rm(dir,{recursive:true,force:true});
    for(const [path,bytes] of wanted){await mkdir(dirname(join(dir,path)),{recursive:true});await writeFile(join(dir,path),bytes);}
  }
}
console.log(JSON.stringify({files:outputs.size,assets:files.size,mode:check?'verified':'synced'}));
